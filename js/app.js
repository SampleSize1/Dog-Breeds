document.addEventListener('keydown', (e) => {
	if (e.metaKey || e.ctrlKey || e.altKey) return;
	if (!$('intro').hidden) {
		if (e.key === 'Escape' || e.key === 'Enter' || e.key === ' ') {
			e.preventDefault();
			intro(false);
		}
		return;
	}
	const typing = e.target && (e.target.tagName === 'INPUT' || e.target.tagName === 'SELECT' || e.target.tagName === 'TEXTAREA');
	if (e.key === 'Escape') {
		document.body.classList.remove('sheet-open');
		setClean(false);
		if (S.mode === 'study' && studyAt) studyGrid();
		return;
	}
	if (typing) return;
	const key = e.key === 'Enter' ? ' ' : e.key === 'ArrowLeft' ? '←' : e.key === 'ArrowRight' ? '→' : e.key.toLowerCase();
	const a = actions.find((x) => x.key === key && x.el && !x.el.disabled);
	if (a) {
		e.preventDefault();
		// a focused button would also fire on Space/Enter: drop focus so it runs once
		if (document.activeElement && document.activeElement.blur) document.activeElement.blur();
		if (a.on) a.on(a.id);
	} else if (key === ' ' && advance) {
		e.preventDefault();
		if (document.activeElement && document.activeElement.blur) document.activeElement.blur();
		advance();
	}
});

