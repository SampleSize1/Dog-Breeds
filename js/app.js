/* Dog Breeds
 *
 * Learn to recognise every dog breed from photos. Three sets (Popular, AKC, Every breed) and the designer crosses, in
 * ten groups, each with three modes:
 *   Study     a grid of the breeds; tap one for its photos, what to look for and its look-alikes
 *   Practice  name the breed in a photo, by picking (the wrong choices are its look-alikes) or typing; misses come back
 *   Test      every breed of the selection once, timed; the best score is kept
 * For a cross the question is its two parent breeds, since a photo can't tell crosses apart.
 *
 * Plain modules, no framework, no build step. What the tool knows is in data/breeds.js (generated by
 * tools-src/dog-breeds/build/) and js/core/ (answer checking, what to ask, the photo lookups); this file is the page.
 * Settings, best tests and how well each breed is known are saved in the browser through /js/progress.js. Every word it
 * shows is in js/text.js, looked up through the site's language module (/js/language.js).
 */
