/* ---------------------------------------------------------------- asking */
/**
 * Put a breed's photo up and wait for an answer. o: { eyebrow, bar, test, onAnswer(right, saidId, extra), onNone }.
 * extra: { spelled, typed, hinted, gaveUp }.
 */
function askBreed(b, o) {
	peek.q = { kind: 'breed', id: b.id };
	peek.answer = b.id;
	const typing = answerBy() === 'type';
	prompt({ eyebrow: o.eyebrow, name: t('which_breed'), meta: typing ? t('type_meta') : t('pick_meta'), bar: o.bar });
	const box = photoBox(b.id, { index: randomPhoto(b.id), quiz: true, none: t('no_photo_title'), onNone: o.onNone });
	show(box);
	photos.resolveLeads([b.id]);
	if (!session.t0) session.t0 = Date.now();
	let done = false;
	const answer = (right, said, extra = {}) => {
		if (done) return;
		done = true;
		o.onAnswer(right, said, extra, box);
	};
	if (!typing) {
		const ids = choices(b, setNow(), lmap);
		peek.q.options = ids;
		setActions(ids.map((id, i) => ({ id, label: nameOf(id), key: String(i + 1), on: () => answer(id === b.id, id) })));
		advance = null;
		return;
	}
	// typing: a box, Check, a hint (practice only) and give up
	let hints = 0;
	const input = h('input', { type: 'text', autocomplete: 'off', autocapitalize: 'words', spellcheck: 'false', enterkeyhint: 'done', placeholder: t('type_ph'), 'aria-label': t('type_aria') });
	const submit = () => {
		const text = input.value.trim();
		if (!text) return;
		const res = check(text, b.id, index);
		if (res.verdict === 'right') return answer(true, b.id, { spelled: res.spelled, hinted: hints > 0 });
		if (res.verdict === 'vague') {
			const opts = res.ids.filter((id) => byId.has(id)).map(nameOf);
			prompt({ eyebrow: o.eyebrow || eyebrow(), name: t('which_one', { word: text }), meta: t('be_specific'), tip: opts.length ? t('could_be', { names: lang.join(opts, 'or') }) : null, state: 'warn', bar: o.bar });
			input.select();
			return;
		}
		answer(false, res.verdict === 'other' ? res.id : null, { typed: text, hinted: hints > 0 });
	};
	input.addEventListener('keydown', (e) => {
		if (e.key === 'Enter' && !e.isComposing) {
			e.preventDefault();
			submit();
		}
	});
	const row = h('div', { class: 'typebox' }, [input, h('button', { class: 'act primary', type: 'button', onclick: submit }, [h('span', { class: 'txt', text: t('check') })])]);
	const extras = [];
	if (!o.test) {
		extras.push({
			id: 'hint',
			label: t('hint'),
			// no key: letters go into the box
			on: () => {
				hints++;
				if (hints >= 3) return answer(false, null, { gaveUp: true, hinted: true });
				prompt({ eyebrow: o.eyebrow || eyebrow(), name: t('which_breed'), meta: hints === 1 ? t('hint_1', { size: t('size.' + b.size).toLowerCase(), kind: t('kind.' + b.group), country: b.country }) : letters(b.name), bar: o.bar });
				input.focus();
			},
		});
	}
	extras.push({ id: 'give-up', label: o.test ? t('skip') : t('show_answer'), on: () => answer(false, null, { gaveUp: true }) });
	setActions(extras, true);
	$('actions').prepend(row);
	advance = null;
	setTimeout(() => input.focus({ preventScroll: true }), 30);
}
/** The second hint: the first letter of each word, the rest as gaps. */
const letters = (name) =>
	name
		.split(' ')
		.map((w) => w[0] + ' ' + '_ '.repeat(Math.max(0, [...w].length - 1)).trim())
		.join('\u2003');

function askCross(c, o) {
	peek.q = { kind: 'cross', id: c.id };
	peek.answer = parentsText(c);
	prompt({ eyebrow: o.eyebrow, name: t('cross_ask', { name: c.name }), meta: t('cross_meta'), bar: o.bar });
	const box = photoBox(c.id, { quiz: false, none: c.name, noneSub: '' });
	show(box);
	if (!session.t0) session.t0 = Date.now();
	const pairs = crossChoices(c, CROSSES);
	peek.q.options = pairs.map((p) => p.map((x) => x.name).join(' + '));
	let done = false;
	setActions(
		pairs.map((p, i) => ({
			id: 'pair' + i,
			label: p.map((x) => x.name).join(' + '),
			key: String(i + 1),
			pair: p,
			on: () => {
				if (done) return;
				done = true;
				o.onAnswer(isRightPair(p, c), 'pair' + i, {}, box);
			},
		}))
	);
	advance = null;
}

/* ---------------------------------------------------------------- practice */
function practice() {
	const mine = run;
	const review = createReview();
	const recent = [];
	const items = poolNow();
	if (!items.length) return emptyPool();
	const next = () => {
		if (mine !== run) return;
		const item = review.due();
		const b = item ? byId.get(item.id) : pickNext(items, known, recent);
		recent.push(b.id);
		const again = item ? eyebrow(t('again')) : null;
		if (crosses()) return askCross(b, { eyebrow: again, onAnswer: (right, said) => after(b, right, said, {}, item) });
		askBreed(b, {
			eyebrow: again,
			onAnswer: (right, said, extra, box) => after(b, right, said, extra, item, box),
			onNone: () => setTimeout(next, 0), // no photo could load: on to another breed
		});
	};
	const after = (b, right, said, extra, item, box) => {
		if (mine !== run) return;
		mark(right);
		flash(right);
		review.record(b.id, right, item);
		learn(b.id, right, extra.hinted);
		const waiting = review.waiting();
		if (crosses()) {
			for (const a of actions) {
				a.el.disabled = true;
				if (a.id === said) a.el.classList.add(right ? 'is-right' : 'is-wrong');
				if (!right && a.pair && isRightPair(a.pair, b)) a.el.classList.add('is-right');
			}
			prompt({
				eyebrow: right ? t('correct') : t('not_quite'),
				name: parentsText(b),
				meta: b.aka.length ? t('also_called', { names: b.aka.join(', ') }) : null,
				tip: t('cross_note', { name: b.name }),
				state: right ? 'ok' : 'bad',
			});
		} else {
			const s = said && said !== b.id ? byId.get(said) : null;
			const tell = s ? tellFor(b.id, s.id, LOOKALIKES) : null;
			let top = right ? (extra.spelled ? t('correct_spelled', { name: b.name }) : t('correct')) : s ? t('you_said', { name: s.name }) : extra.gaveUp ? t('the_answer') : extra.typed ? t('not_a_breed', { text: extra.typed }) : t('not_quite');
			if (right && extra.hinted) top = t('correct_hinted');
			prompt({
				eyebrow: top,
				name: b.name,
				meta: factsLine(b) + (waiting ? ' · ' + t('to_come_back', { n: waiting }) : ''),
				tip: esc(b.note) + (tell ? `<span class="tell">${esc(tell)}</span>` : s ? `<span class="tell">${esc(t('that_was', { name: s.name, note: s.note }))}</span>` : ''),
				state: right ? 'ok' : 'bad',
			});
			// the photo stays, with arrows to the breed's other photos to look at before moving on
			if (box) box.reveal();
		}
		setActions([nextButton(t('next'), next)], true);
		advance = next;
	};
	next();
}

/* ---------------------------------------------------------------- test */
function test() {
	const mine = run;
	const items = shuffle(poolNow());
	if (!items.length) return emptyPool();
	const missed = [];
	let skipped = 0;
	let i = 0;
	const step = () => {
		if (mine !== run) return;
		if (i >= items.length) return finish();
		const b = items[i];
		const n = items.length;
		const opts = {
			eyebrow: eyebrow(t('n_of', { i: i + 1, n })),
			bar: i / n,
			test: true,
			onAnswer: (right, said, extra) => {
				if (mine !== run) return;
				for (const a of actions) {
					a.on = null;
					if (a.el) {
						a.el.disabled = true;
						if (a.id === said) a.el.classList.add(right ? 'is-right' : 'is-wrong');
						if (!right && (crosses() ? a.pair && isRightPair(a.pair, b) : a.id === b.id)) a.el.classList.add('is-right');
					}
				}
				mark(right);
				flash(right);
				known[b.id] = right ? Math.max(LEARNED, known[b.id] || 0) : 0;
				saved.set('known', known);
				if (!right) missed.push({ id: b.id, said: said && byId.has(said) ? said : null, typed: extra.typed || null });
				// a wrong typed answer shows the right name for a moment
				if (!right && answerBy() === 'type') prompt({ eyebrow: opts.eyebrow, name: b.name, meta: t('test_was'), bar: opts.bar, state: 'bad' });
				i++;
				setTimeout(step, right ? 420 : answerBy() === 'type' || crosses() ? 1300 : 900);
			},
			onNone: () => {
				skipped++;
				i++;
				setTimeout(step, 0);
			},
		};
		if (crosses()) askCross(b, opts);
		else askBreed(b, opts);
		if (items[i + 1]) preload(items[i + 1].id);
	};
	const finish = () => {
		session.frozen = elapsed();
		const total = items.length - skipped;
		const score = total - missed.length;
		const time = session.frozen;
		const key = bestKey();
		const old = bests[key];
		const better = !old || score / total > old.score / old.total || (score / total === old.score / old.total && time < old.time);
		if (better && total) {
			bests[key] = { score, total, time };
			saved.set('best', bests);
		}
		peek.q = null;
		peek.result = { score, total, skipped };
		const perfect = score === total;
		prompt({
			eyebrow: eyebrow(t('result')),
			name: perfect ? t('perfect') : t('score_line', { score, total }),
			meta: t('in_time', { time: clock(time) }) + (better && old ? ' · ' + t('new_best') : '') + (skipped ? ' · ' + t('skipped_n', { n: skipped }) : ''),
			tip: missed.length ? t('missed_below') : null,
			state: perfect ? 'ok' : null,
			bar: 1,
		});
		show(
			h('div', { class: 'summary' }, [
				h('div', { class: 'tiles' }, [
					h('div', { class: 'chip' + (perfect ? ' good' : '') }, [h('small', { text: t('score') }), h('b', { text: `${score}/${total}` })]),
					h('div', { class: 'chip' }, [h('small', { text: t('time') }), h('b', { text: clock(time) })]),
				]),
				missed.length
					? h(
							'div',
							{ class: 'misses' },
							missed.map((m) =>
								h('button', { type: 'button', title: t('study_it'), onclick: () => openStudy(m.id) }, [
									h('b', { text: nameOf(m.id) }),
									h('span', { text: m.said ? t('you_said_short', { name: nameOf(m.said) }) : m.typed ? '“' + m.typed + '”' : t('skipped') }),
								])
							)
						)
					: h('p', { class: 'note', text: t('nothing_missed') }),
			])
		);
		setActions(
			[
				{ id: 'again', label: t('try_again'), key: ' ', primary: true, on: start },
				{ id: 'practice', label: t('mode_practice'), key: 'p', on: () => setMode('practice') },
			],
			true
		);
		advance = null;
		fillRail();
		showBest();
		showStats();
	};
	step();
}

/* ---------------------------------------------------------------- study */
let studyAt = null; // the breed open in Study, or null for the grid
function studyGrid() {
	studyAt = null;
	const gridRun = run;
	const items = poolNow();
	if (!items.length) return emptyPool();
	const learnedN = learnedIn(items, known);
	prompt({
		name: crosses() ? t('crosses_title', { n: items.length }) : S.group === 'all' ? t('set_title.' + S.set, { n: items.length }) : t('group_title', { group: groupLabel(S.group), n: items.length }),
		meta: t('learned_n', { n: learnedN, total: items.length }),
		tip: t(crosses() ? 'crosses_tip' : 'study_tip'),
	});
	const grid = h('div', { class: 'grid' });
	const card = (b) => {
		const thumb = h('div', { class: 'thumb', 'data-id': b.id, 'data-initial': b.name[0] });
		fillThumb(thumb);
		const sub = crosses() ? parentsText(b) : t('size.' + b.size) + ' · ' + b.country;
		return h('button', { class: 'card' + ((known[b.id] || 0) >= LEARNED ? ' is-known' : ''), type: 'button', 'data-id': b.id, onclick: () => studyOne(b.id) }, [thumb, h('div', { class: 'lbl' }, [h('b', { text: b.name }), h('small', { text: sub })])]);
	};
	if (!crosses() && S.group === 'all') {
		for (const g of GROUPS) {
			const list = items.filter((b) => b.group === g);
			if (!list.length) continue;
			grid.append(h('div', { class: 'head', text: `${groupLabel(g)} · ${list.length}` }), ...list.map(card));
		}
	} else grid.append(...items.map(card));
	show(grid);
	setActions([{ id: 'practice', label: t('practise_these'), key: 'p', primary: true, on: () => setMode('practice') }], true);
	advance = null;
	// thumbnails for breeds without a Wikidata photo arrive with their Wikipedia lead photos
	const missing = items.filter((b) => !photos.list(b.id).length).map((b) => b.id);
	if (missing.length) photos.resolveLeads(missing).then(() => S.mode === 'study' && studyAt == null && run === gridRun && refreshThumbs(grid));
}
function refreshThumbs(grid) {
	for (const thumb of grid.querySelectorAll('.thumb.none')) fillThumb(thumb);
}
/** A grid card's picture: the breed's first photo; one that won't load is dropped and the next tried, and with none
 * left the card shows the breed's initial. */
function fillThumb(thumb) {
	const first = photos.list(thumb.dataset.id)[0];
	thumb.classList.toggle('none', !first);
	thumb.querySelector('img')?.remove();
	if (!first) return;
	thumb.append(
		h('img', {
			src: photoUrl(first, 330),
			alt: '',
			loading: 'lazy',
			decoding: 'async',
			style: 'width:100%;height:100%;object-fit:cover;display:block',
			onerror: () => {
				photos.drop(first);
				fillThumb(thumb);
			},
		}),
	);
}
function studyOne(id) {
	studyAt = id;
	const b = byId.get(id);
	const items = poolNow();
	const at = items.findIndex((x) => x.id === id);
	photos.resolveLeads([id]);
	const box = photoBox(id, { nav: true, none: b.name, noneSub: crosses() ? '' : null });
	let info;
	if (crosses()) {
		prompt({ eyebrow: eyebrow(t('n_of', { i: at + 1, n: items.length })), name: b.name, meta: t('cross_short') });
		info = h('div', { class: 'info' }, [
			h('h2', { text: b.name }),
			b.aka.length ? h('p', { class: 'aka', text: t('also_called', { names: b.aka.join(', ') }) }) : null,
			h('div', { class: 'parents' }, [h('span', { text: b.parents[0].name }), h('i', { text: '+' }), h('span', { text: b.parents[1].name })]),
			h('p', { class: 'look', text: t('cross_note', { name: b.name }) }),
			b.wiki ? h('div', { class: 'links' }, [h('a', { href: articleUrl(b.wiki), target: '_blank', rel: 'noopener', text: t('wikipedia') })]) : null,
		]);
	} else {
		prompt({ eyebrow: eyebrow(t('n_of', { i: at + 1, n: items.length })), name: b.name, meta: factsLine(b) });
		const groups = tellsOf(id, LOOKALIKES);
		info = h('div', { class: 'info' }, [
			h('h2', { text: b.name }),
			b.aka.length ? h('p', { class: 'aka', text: t('also_called', { names: b.aka.join(', ') }) }) : null,
			chips(b),
			h('h3', { text: t('look_for') }),
			h('p', { class: 'look', text: b.note }),
			groups.length ? h('h3', { text: t('mixed_up_with') }) : null,
			groups.length
				? h(
						'div',
						{ class: 'alikes' },
						groups.map((g) =>
							h('div', { class: 'alike' }, [
								h(
									'div',
									{ class: 'who' },
									g.ids.filter((x) => x !== id).map((x) => h('button', { type: 'button', text: nameOf(x), onclick: () => openStudy(x) }))
								),
								h('p', { text: g.tell }),
							])
						)
					)
				: null,
			h('div', { class: 'links' }, [h('a', { href: articleUrl(b.wiki), target: '_blank', rel: 'noopener', text: t('wikipedia') })]),
		]);
	}
	show(h('div', { class: 'detail' }, [box, info]));
	const go = (d) => items.length && studyOne(items[(at + d + items.length) % items.length].id);
	setActions(
		[
			{ id: 'back', label: t('all_breeds'), key: 'b', on: studyGrid },
			{ id: 'prev', label: t('prev_breed'), key: '←', on: () => go(-1) },
			{ id: 'next', label: t('next_breed'), key: '→', on: () => go(1) },
		],
		true
	);
	advance = () => box.step(1);
	peek.study = id;
}
/** Open a breed in Study, from anywhere (a look-alike, a missed test question), widening the set if it isn't in it. */
function openStudy(id) {
	const b = byId.get(id);
	if (!crosses() && b && !pool(BREEDS, S.set, S.group).some((x) => x.id === id)) {
		if (!pool(BREEDS, S.set, 'all').some((x) => x.id === id)) S.set = 'every';
		S.group = 'all';
	}
	S.mode = 'study';
	saveSettings();
	start({ open: id });
}
